// End-to-end smoke test against a running preview server (npm run build && npx vite preview --port 4173).
//   node scripts/e2e.mjs [shotDir]
import { chromium } from 'playwright-core';
import fs from 'node:fs';
const shotDir = process.argv[2];
if (shotDir) fs.mkdirSync(shotDir, { recursive: true });
const base = process.env.BASE || 'http://localhost:4173/';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
const requests = [];
page.on('request', (r) => requests.push(r.url()));
let step = 0;
const shot = async (name) => { if (shotDir) await page.screenshot({ path: `${shotDir}/${String(++step).padStart(2, '0')}-${name}.png` }); };
const ok = (cond, msg) => { if (!cond) { console.error('FAIL:', msg); process.exitCode = 1; } else console.log('ok  :', msg); };

await page.goto(base + '#/');
await page.waitForSelector('.year-card');
ok((await page.locator('.year-card').count()) === 22, '22 papers listed');
await page.fill('#year-search', '2021');
ok((await page.locator('.year-card').count()) === 1, 'search narrows to one year');
await page.click('.year-card >> text=Start test');
await page.waitForSelector('.start-card');
await shot('start');
await page.check('input[value="untimed"]');
await page.click('#start-btn');
await page.waitForSelector('.exam');
await shot('exam');
ok(await page.locator('.problem-tab').count() === 4, 'four problem tabs');
ok(await page.locator('.answers input').count() === 12, 'twelve answer inputs');
ok(!(await page.locator('body').innerText()).includes('15163'), 'official answers are not visible before submit');
await page.fill('#in-p1a-v', '65');
await page.fill('#in-p1b-v', '15162');
await page.click('button[aria-label="Mark problem 1 part c for review"]');
await page.click('.problem-tab >> nth=1');
await page.fill('#in-p2a-v', '2');
// reload: attempt should be restored
await page.reload();
await page.waitForSelector('.start-card');
await page.click('text=Resume attempt');
await page.waitForSelector('.exam');
ok((await page.inputValue('#in-p1a-v')) === '65', 'answers restored after refresh');
ok((await page.inputValue('#in-p2a-v')) === '2', 'second problem answer restored');
await shot('exam-restored');
await page.click('button:has-text("Submit")');
await page.waitForSelector('dialog[open]');
await shot('confirm');
await page.click('dialog [data-action="submit"]');
await page.waitForSelector('.summary-grid');
await shot('results');
const text = await page.locator('main').innerText();
ok(/Correct/.test(text) && text.includes('15163'), 'results show the official answers');
// multi-field paper (2012) and sub-path hosting
await page.goto(base + '#/');
await page.waitForSelector('.year-card');
await page.fill('#year-search', '2012');
await page.click('.year-card >> text=Start test');
await page.waitForSelector('.start-card');
await page.check('input[value="untimed"]');
await page.click('#start-btn');
await page.waitForSelector('.exam');
ok((await page.locator('#in-p1a-minN').count()) === 1, '2012 problem 1 has labelled sub-fields');
await page.fill('#in-p1a-minN', '28'); await page.fill('#in-p1a-maxN', '28'); await page.fill('#in-p1a-colour', 'White');
await page.click('button:has-text("Submit")');
await page.click('dialog [data-action="submit"]');
await page.waitForSelector('.summary-grid');
const t2 = await page.locator('main').innerText();
ok(/Correct/.test(t2) && /Min N: 28/.test(t2), '2012 multi-field part marked correct with official answer shown');
console.log('external requests:', requests.filter((u) => !u.startsWith(base) && !u.startsWith('data:')).join(', ') || 'none');
console.log(errors.length ? errors.join('\n') : 'no console errors');
await browser.close();
